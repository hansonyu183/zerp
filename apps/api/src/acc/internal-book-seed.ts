import type { AccSettlementPurpose, AccSubjectDimension } from '@zerp/model'
import type { AccSubjectTemplateLine } from './service.ts'

export const internalBookId = '01M2R3C0000000000000000000'

function subject(
  code: string,
  name: string,
  balanceDirection: 'DEBIT' | 'CREDIT',
  requiredDimensions: AccSubjectDimension[] = [],
  settlementPurpose: AccSettlementPurpose = 'NONE',
): AccSubjectTemplateLine {
  return {
    code,
    name,
    balanceDirection,
    ...(code.includes('.')
      ? { parentCode: code.slice(0, code.lastIndexOf('.')) }
      : {}),
    requiredDimensions,
    inventoryQuantity: false,
    settlementPurpose,
  }
}

